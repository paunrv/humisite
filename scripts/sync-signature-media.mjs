/**
 * Sync ONLY the exact curated Signature Events stills.
 *
 * Sources: media/signature-events/ (exact filenames below).
 * No fallbacks. No similar-asset search. Missing files are skipped.
 *
 * Writes src/lib/signature-events-media.generated.ts so the app
 * never references paths that were not copied from curated sources.
 */
import {
  copyFileSync,
  existsSync,
  mkdirSync,
  readdirSync,
  writeFileSync,
} from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const mediaDir = path.join(root, "media", "signature-events");
const generatedPath = path.join(
  root,
  "src",
  "lib",
  "signature-events-media.generated.ts",
);

/** Case-insensitive exact filename lookup (first match wins). */
function findExact(dir, filenames) {
  if (!existsSync(dir)) return null;
  const names = Array.isArray(filenames) ? filenames : [filenames];
  const entries = readdirSync(dir);
  for (const filename of names) {
    const lower = filename.toLowerCase();
    for (const entry of entries) {
      if (entry.toLowerCase() === lower) return path.join(dir, entry);
    }
  }
  return null;
}

/**
 * Exact curated stills only.
 * Do NOT map bootcamp *-03.jpg extras.
 * Sunday Funday poster may come from "Sunday Funday 03.jpg".
 * Timeline display order is newest→oldest in signature-events.ts;
 * year keys here stay chronological for folder layout.
 */
