/**
 * Sync ONLY the exact curated Signature Events stills.
 *
 * Sources: media/signature-events/ (exact filenames below).
 * No fallbacks. No similar-asset search. Missing files are skipped.
 *
 * Writes src/lib/signature-events-media.generated.ts so the app
 * never references paths that were not copied from curated sources.
 */
import {
  copyFileSync,
  existsSync,
  mkdirSync,
  readdirSync,
  writeFileSync,
} from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const mediaDir = path.join(root, "media", "signature-events");
const generatedPath = path.join(
  root,
  "src",
  "lib",
  "signature-events-media.generated.ts",
);

/** Case-insensitive exact filename lookup. */
function findExact(dir, filename) {
  if (!existsSync(dir)) return null;
  const lower = filename.toLowerCase();
  for (const entry of readdirSync(dir)) {
    if (entry.toLowerCase() === lower) return path.join(dir, entry);
  }
  return null;
}

/** Exact curated stills only. Do NOT map *-03.jpg. */
const STILL_MAPPINGS = [
  {
    year: "2018",
    source: "1st-tkdolympicbootcamp.jpg",
    field: "poster",
  },
  {
    year: "2018",
    source: "1st-tkdolympicbootcamp-01.jpg",
    field: "photo1",
  },
  {
    year: "2018",
    source: "1st-tkdolympicbootcamp-02.jpg",
    field: "photo2",
  },
  {
    year: "2019",
    source: "2nd-tkdolympicbootcamp.jpg",
    field: "poster",
  },
  {
    year: "2019",
    source: "2nd-tkdolympicbootcamp-01.jpg",
    field: "photo1",
  },
  {
    year: "2019",
    source: "2nd-tkdolympicbootcamp-02.jpg",
    field: "photo2",
  },
  {
    year: "2023",
    source: "ki-games.jpg",
    field: "poster",
  },
];

/** @type {Record<string, Record<string, string>>} */
const mediaByYear = {};

mkdirSync(mediaDir, { recursive: true });

let copied = 0;
let missing = 0;

for (const { year, source, field } of STILL_MAPPINGS) {
  const from = findExact(mediaDir, source);
  const outDir = path.join(root, "public", "signature-events", year);
  const to = path.join(outDir, source);
  mkdirSync(outDir, { recursive: true });

  if (!from) {
    missing += 1;
    console.warn(`sync-signature-media: missing exact file "${source}"`);
    continue;
  }

  copyFileSync(from, to);
  mediaByYear[year] ??= {};
  mediaByYear[year][field] = `/signature-events/${year}/${source}`;
  copied += 1;
  console.log(
    `sync-signature-media: ${source} → public/signature-events/${year}/${source}`,
  );
}

writeFileSync(
  generatedPath,
  `/**
 * AUTO-GENERATED by scripts/sync-signature-media.mjs (+ sync-signature-recaps.mjs)
 * Do not edit by hand. Only exact curated assets appear here.
 */

export type CuratedEventMedia = {
  poster?: string;
  photo1?: string;
  photo2?: string;
  recapVideo?: string;
  recapThumbnail?: string;
};

export const CURATED_EVENT_MEDIA: Record<string, CuratedEventMedia> = ${JSON.stringify(
    mediaByYear,
    null,
    2,
  )};
`,
  "utf8",
);

console.log(
  `sync-signature-media: ${copied} stills synced (${missing} missing)`,
);
