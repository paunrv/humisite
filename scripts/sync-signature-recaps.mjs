/**
 * Sync ONLY exact curated Signature Events recap videos.
 * No similar-asset fallbacks.
 *
 * Merges into src/lib/signature-events-media.generated.ts
 * (run after sync-signature-media.mjs).
 */
import {
  copyFileSync,
  existsSync,
  mkdirSync,
  readFileSync,
  readdirSync,
  writeFileSync,
} from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const generatedPath = path.join(
  root,
  "src",
  "lib",
  "signature-events-media.generated.ts",
);

const searchDirs = [
  path.join(root, "media", "signature-events"),
  path.join(root, "video", "signature-events"),
  path.join(root, "video"),
];

/** Exact curated recaps. `aliases` are alternate exact filenames (same asset). */
const RECAP_MAPPINGS = [
  { year: "2022", source: "Ruumble Humi.mp4" },
  { year: "2023", source: "ki games.mp4" },
  {
    year: "2024",
    source: "Taekwondo Games.mp4",
    aliases: ["taekwondo-games.mp4"],
  },
];

function findExact(filename, aliases = []) {
  const candidates = [filename, ...aliases].map((n) => n.toLowerCase());
  const dirs = [];
  for (const dir of searchDirs) {
    if (!existsSync(dir)) continue;
    dirs.push(dir);
    for (const entry of readdirSync(dir, { withFileTypes: true })) {
      if (entry.isDirectory()) dirs.push(path.join(dir, entry.name));
    }
  }
  for (const d of dirs) {
    if (!existsSync(d)) continue;
    for (const entry of readdirSync(d)) {
      if (!entry.toLowerCase().endsWith(".mp4")) continue;
      if (candidates.includes(entry.toLowerCase())) {
        return path.join(d, entry);
      }
    }
  }
  return null;
}

function publicUrl(year, filename) {
  return `/signature-events/${year}/${filename
    .split("/")
    .map((seg) => encodeURIComponent(seg))
    .join("/")}`;
}

/** @type {Record<string, Record<string, string>>} */
let mediaByYear = {};

if (existsSync(generatedPath)) {
  const raw = readFileSync(generatedPath, "utf8");
  const marker = "CURATED_EVENT_MEDIA";
  const idx = raw.indexOf(marker);
  const start = raw.indexOf("{", idx);
  if (start !== -1) {
    let depth = 0;
    let end = -1;
    for (let i = start; i < raw.length; i++) {
      if (raw[i] === "{") depth++;
      else if (raw[i] === "}") {
        depth--;
        if (depth === 0) {
          end = i + 1;
          break;
        }
      }
    }
    if (end !== -1) {
      try {
        mediaByYear = JSON.parse(raw.slice(start, end));
      } catch {
        mediaByYear = {};
      }
    }
  }
}

let copied = 0;
let missing = 0;

for (const { year, source, aliases = [] } of RECAP_MAPPINGS) {
  const from = findExact(source, aliases);
  const outDir = path.join(root, "public", "signature-events", year);
  // Always publish under the canonical curated filename.
  const to = path.join(outDir, source);
  mkdirSync(outDir, { recursive: true });

  if (!from) {
    missing += 1;
    console.warn(`sync-signature-recaps: missing exact file "${source}"`);
    continue;
  }

  copyFileSync(from, to);
  mediaByYear[year] ??= {};
  mediaByYear[year].recapVideo = publicUrl(year, source);
  if (mediaByYear[year].poster) {
    mediaByYear[year].recapThumbnail = mediaByYear[year].poster;
  }
  copied += 1;
  console.log(
    `sync-signature-recaps: ${path.relative(root, from)} → public/signature-events/${year}/${source}`,
  );
}

writeFileSync(
  generatedPath,
  `/**
 * AUTO-GENERATED by scripts/sync-signature-media.mjs (+ sync-signature-recaps.mjs)
 * Do not edit by hand. Only exact curated assets appear here.
 */

export type CuratedEventMedia = {
  poster?: string;
  photo1?: string;
  photo2?: string;
  recapVideo?: string;
  recapThumbnail?: string;
};

export const CURATED_EVENT_MEDIA: Record<string, CuratedEventMedia> = ${JSON.stringify(
    mediaByYear,
    null,
    2,
  )};
`,
  "utf8",
);

console.log(
  `sync-signature-recaps: ${copied} videos synced (${missing} missing)`,
);
